#!/usr/bin/env python3
"""Build the canonical front-maw layer atlas from owner-derived packed layers.

The packed source is generated by prep_maws.py: R=upper, G=lower,
B=emissive eyes.  Values 40+tone*30 identify the opaque part body and its
seven-colour detail tone.  This builder never edits either owner source.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw


PALETTE = (
    (0x00, 0x00, 0x00),
    (0x3E, 0x15, 0x00),
    (0x70, 0x27, 0x00),
    (0xAD, 0x42, 0x01),
    (0xE5, 0x78, 0x07),
    (0xF9, 0xBD, 0x2B),
    (0xFD, 0xE7, 0x66),
)
LAYERS = ("body", "detail", "normal", "emissive")
PADDING = 2


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tone(value):
    return max(0, min(6, int(round((value - 40) / 30))))


def part_images(source, channel):
    rgba = source.convert("RGBA")
    width, height = rgba.size
    pixels = rgba.load()
    mask = [[pixels[x, y][channel] >= 40 for x in range(width)] for y in range(height)]

    body = Image.new("RGBA", rgba.size)
    detail = Image.new("RGBA", rgba.size)
    normal = Image.new("RGBA", rgba.size)
    emissive = Image.new("RGBA", rgba.size)
    body_px, detail_px = body.load(), detail.load()
    normal_px, emissive_px = normal.load(), emissive.load()

    def occupied(x, y):
        return 0 <= x < width and 0 <= y < height and mask[y][x]

    for y in range(height):
        for x in range(width):
            if not mask[y][x]:
                continue
            value = pixels[x, y][channel]
            body_px[x, y] = (0, 0, 0, 255)
            t = tone(value)
            if t:
                detail_px[x, y] = (*PALETTE[t], 255)
            # A deterministic bevel normal from the hard silhouette. Image Y
            # points down, while tangent-space +Y must point up.
            nx = float(occupied(x - 1, y) - occupied(x + 1, y))
            ny = float(occupied(x, y + 1) - occupied(x, y - 1))
            nz = 2.0
            length = math.sqrt(nx * nx + ny * ny + nz * nz)
            normal_px[x, y] = (
                round(127.5 + 127.5 * nx / length),
                round(127.5 + 127.5 * ny / length),
                round(127.5 + 127.5 * nz / length),
                255,
            )
            if pixels[x, y][2] > 0:
                emissive_px[x, y] = (*PALETTE[6], 255)
    return {"body": body, "detail": detail, "normal": normal, "emissive": emissive}


def build(source_path, owner_path, output):
    source = Image.open(source_path).convert("RGBA")
    width, height = source.size
    parts = (("upper", 0), ("lower", 1))
    built = {name: part_images(source, channel) for name, channel in parts}

    stride_x, stride_y = width + PADDING * 2, height + PADDING * 2
    atlas = Image.new("RGBA", (PADDING + len(LAYERS) * stride_x, PADDING + len(parts) * stride_y))
    manifest_parts = []
    hinge = [width // 2, 168]
    for row, (part_id, _) in enumerate(parts):
        rects = {}
        for col, layer in enumerate(LAYERS):
            x = PADDING + col * stride_x
            y = PADDING + row * stride_y
            atlas.alpha_composite(built[part_id][layer], (x, y))
            rects[layer] = [x, y, width, height]
        manifest_parts.append({
            "id": part_id,
            "pivot": hinge,
            "parent": None if part_id == "upper" else "upper",
            "joint": "fixed" if part_id == "upper" else "hinge",
            "rects": rects,
        })

    # Runtime-independent preview: opaque black body plus palette detail and
    # owner-authored emissive eyes. Nearest scaling preserves the art grid.
    preview = Image.new("RGBA", source.size)
    for part_id, _ in parts:
        preview.alpha_composite(built[part_id]["body"])
        preview.alpha_composite(built[part_id]["detail"])
        preview.alpha_composite(built[part_id]["emissive"])
    preview = preview.resize((width * 3, height * 3), Image.Resampling.NEAREST)

    owner = Image.open(owner_path).convert("RGB")
    evidence_height = preview.height
    owner_width = round(owner.width * evidence_height / owner.height)
    owner_view = owner.resize((owner_width, evidence_height), Image.Resampling.LANCZOS)
    evidence = Image.new("RGB", (owner_width + preview.width, evidence_height + 24), "black")
    evidence.paste(owner_view, (0, 24))
    evidence.paste(preview.convert("RGB"), (owner_width, 24))
    draw = ImageDraw.Draw(evidence)
    draw.text((6, 6), "OWNER REFERENCE", fill=PALETTE[6])
    draw.text((owner_width + 6, 6), "DERIVED 4-LAYER BASELINE", fill=PALETTE[6])

    output.mkdir(parents=True, exist_ok=True)
    atlas.save(output / "maw_front_atlas.png", optimize=False, compress_level=9)
    preview.save(output / "maw_front_preview.png", optimize=False, compress_level=9)
    evidence.save(output / "maw_front_evidence.png", optimize=False, compress_level=9)

    manifest = {
        "schema": "abyss.asset.v1",
        "id": "maw_front_v1",
        "kind": "attack",
        "type": "owner_front_maw",
        "stage": 4,
        "zones": [4],
        "layer": "play",
        "sizeArt": [width, height],
        "atlas": {"file": "maw_front_atlas.png", "size": list(atlas.size), "padding": PADDING},
        "pivot": hinge,
        "hitbox": {"circle": [width // 2, height // 2, min(width, height) // 3]},
        "sockets": {"mouthHinge": hinge, "eyeL": [59, 107], "eyeR": [158, 105]},
        "parts": manifest_parts,
        "animation": {"status": "UNKNOWN", "reason": "baseline parts only; no runtime articulation claimed"},
        "source": {
            "kind": "owner_sketch_derived_layers",
            "path": "abyss-glow/sketches/maw_front_layers.png",
            "sha256": sha256(source_path),
            "owner_reference": "abyss-glow/sketches/maw_front_owner.png",
            "owner_reference_sha256": sha256(owner_path),
            "derivation": "abyss-glow/sketches/prep_maws.py",
        },
        "license": {
            "status": "UNKNOWN",
            "note": "Owner-provided project source; no explicit SPDX grant recorded in repository.",
        },
        "limitations": [
            "Technical extraction is not owner artistic approval.",
            "Normal map is deterministic bevel baseline pending manual art review.",
            "Physical iPhone rendering and FPS are UNKNOWN.",
        ],
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--owner", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    manifest = build(args.source, args.owner, args.output)
    print(json.dumps({"status": "BUILT_NOT_OWNER_APPROVED", "id": manifest["id"]}))


if __name__ == "__main__":
    main()
